-- Unity Catalog governance for the lab.
-- Run from a warehouse after catalogs exist.
-- Docs checked 2026-10-27:
--   https://learn.microsoft.com/en-us/azure/databricks/data-governance/unity-catalog/row-and-column-filters
-- Analysts are masked. Platform admins are not. Prove both with the SELECT at the bottom.

CREATE CATALOG IF NOT EXISTS dev;
CREATE CATALOG IF NOT EXISTS prod;
CREATE CATALOG IF NOT EXISTS sandbox;

CREATE SCHEMA IF NOT EXISTS prod.bronze COMMENT 'Raw public FDIC extracts. Append-only.';
CREATE SCHEMA IF NOT EXISTS prod.silver COMMENT 'Conformed public FDIC entities.';
CREATE SCHEMA IF NOT EXISTS prod.gold COMMENT 'Business tables for Genie and the regulatory agent.';
CREATE SCHEMA IF NOT EXISTS prod.security COMMENT 'Masks, row filters, and audit helpers.';
CREATE SCHEMA IF NOT EXISTS sandbox.scratch COMMENT 'Personal experimentation. Not a source of record.';

ALTER SCHEMA prod.gold SET TAGS ('domain' = 'bank-supervision', 'data_classification' = 'public');

-- Synthetic PII. The comment is part of the control: reviewers must see the label.
CREATE TABLE IF NOT EXISTS prod.gold.synthetic_complaints (
  complaint_id STRING NOT NULL COMMENT 'Synthetic id. Not an FDIC complaint id.',
  data_origin STRING NOT NULL COMMENT 'Always synthetic-faker in this lab.',
  customer_name STRING COMMENT 'Fake name from Faker. Masked for analysts.',
  ssn STRING COMMENT 'Fake SSN from Faker. Masked for analysts.',
  email STRING COMMENT 'Fake email. Masked for analysts.',
  phone STRING,
  state STRING,
  product STRING,
  channel STRING,
  narrative STRING,
  opened_date DATE
)
COMMENT 'SYNTHETIC PII. Generated by Faker. Not a real customer. Used only to demonstrate column masks.'
TBLPROPERTIES ('delta.enableChangeDataFeed' = 'true');

ALTER TABLE prod.gold.synthetic_complaints SET TAGS (
  'pii' = 'true',
  'sensitivity' = 'confidential',
  'data_origin' = 'synthetic'
);

CREATE OR REPLACE FUNCTION prod.security.mask_ssn(ssn STRING)
RETURNS STRING
RETURN CASE
  WHEN is_account_group_member('dbx-platform-admins') THEN ssn
  ELSE '***-**-' || right(coalesce(ssn, '0000'), 4)
END;

CREATE OR REPLACE FUNCTION prod.security.mask_name(name STRING)
RETURNS STRING
RETURN CASE
  WHEN is_account_group_member('dbx-platform-admins') THEN name
  ELSE 'REDACTED'
END;

CREATE OR REPLACE FUNCTION prod.security.mask_email(email STRING)
RETURNS STRING
RETURN CASE
  WHEN is_account_group_member('dbx-platform-admins') THEN email
  ELSE 'redacted@example.invalid'
END;

ALTER TABLE prod.gold.synthetic_complaints ALTER COLUMN ssn SET MASK prod.security.mask_ssn;
ALTER TABLE prod.gold.synthetic_complaints ALTER COLUMN customer_name SET MASK prod.security.mask_name;
ALTER TABLE prod.gold.synthetic_complaints ALTER COLUMN email SET MASK prod.security.mask_email;

-- Row filter: analysts in a named state see only that state's synthetic rows.
-- Default (no group match) returns TRUE so admins and engineers are not locked out.
CREATE OR REPLACE FUNCTION prod.security.filter_complaints_by_state(state STRING)
RETURNS BOOLEAN
RETURN CASE
  WHEN is_account_group_member('dbx-platform-admins') THEN TRUE
  WHEN is_account_group_member('dbx-analysts-ny') THEN state = 'NY'
  ELSE TRUE
END;

ALTER TABLE prod.gold.synthetic_complaints
SET ROW FILTER prod.security.filter_complaints_by_state ON (state);

-- Public gold tables. No mask. Safe for Genie and the agent.
CREATE TABLE IF NOT EXISTS prod.gold.bank_failures (
  cert INT,
  name STRING,
  city STRING,
  state STRING,
  fail_date DATE,
  assets_at_failure_thousands DOUBLE,
  ingested_at TIMESTAMP
)
COMMENT 'Public FDIC failed-bank list from api.fdic.gov/banks/failures. Not customer data.';

CREATE TABLE IF NOT EXISTS prod.gold.institutions (
  cert INT,
  name STRING,
  state STRING,
  city STRING,
  active INT,
  total_assets DOUBLE,
  report_date DATE
)
COMMENT 'Public FDIC institution snapshot from api.fdic.gov/banks/institutions.';
